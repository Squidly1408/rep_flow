enum ViewAngle { front, side }

class Exercise {
  const Exercise({
    required this.id,
    required this.name,
    required this.cue,
    required this.defaultReps,
    required this.tempo,
    required this.view,
    required this.start,
    required this.end,
  });

  /// Stable key used for saved settings — don't rename.
  final String id;
  final String name;
  final String cue;
  final int defaultReps;

  /// Time to move from [start] to [end] (one half of a rep).
  final Duration tempo;
  final ViewAngle view;
  final Pose start;
  final Pose end;
}


